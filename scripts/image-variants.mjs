// Generates the intermediate image variants the service and care cards need,
// and the width manifest that lets the build write a correct srcset for them.
//
// Run with `node scripts/image-variants.mjs` after adding or replacing a card
// image, then commit both the new files and the regenerated manifest. This is a
// prepare-once step, not part of `npm run build`: it needs cwebp, which the
// Cloudflare builder does not have, so the variants ship as committed assets.
//
// Why this exists: the cards are laid out at roughly 175 CSS px on the smallest
// breakpoint, but every one of these files was being served at its full 640 to
// 1200 px intrinsic width, because site/final-home.mjs only emitted a srcset for
// hero.webp. Lighthouse measured 355 KiB of waste from that on the homepage
// alone. These variants give the browser something sized for the slot it is
// actually filling.

import fs from 'node:fs';
import {execFileSync} from 'node:child_process';

// The widths worth generating. 440 covers a phone card at 2x; 660 covers a
// tablet card. Anything wider competes with the source file, which the srcset
// already offers as its last step.
const WIDTHS = [440, 660];
const QUALITY = '80';

// Every image rendered through compactServiceCard or simpleCare. hero.webp and
// hero-collage.webp are deliberately absent: both already carry hand-built
// multi-step srcsets, and their files are named differently from the rest.
const TARGETS = [
  'assets/img/editorial/bathroom.webp',
  'assets/img/editorial/blinds-v2.webp',
  'assets/img/editorial/carpet-v2.webp',
  'assets/img/editorial/chimney.webp',
  'assets/img/editorial/curtains-v2.webp',
  'assets/img/editorial/floor-v2.webp',
  'assets/img/editorial/fridge-v2.webp',
  'assets/img/editorial/kitchen.webp',
  'assets/img/editorial/mattress-v2.webp',
  'assets/img/editorial/sofa.webp',
  'assets/img/editorial/wooden-floor.webp',
  'assets/img/services/ac-services.webp',
  'assets/img/services/balcony-cleaning.webp',
  'assets/img/services/chandelier-cleaning.webp',
  'assets/img/services/commercial-cleaning.webp',
  'assets/img/services/exhaust-fan-cleaning.webp',
  'assets/img/services/gas-stove-cleaning.webp',
  'assets/img/services/jet-washing.webp',
  'assets/img/services/newborn-prep-cleaning.webp',
  'assets/img/services/pool-cleaning.webp',
  'assets/img/services/post-construction-cleaning.webp',
  'assets/img/services/post-renovation-cleaning.webp',
  'assets/img/services/recurring-cleaning.webp',
  'assets/img/services/sanitisation-service.webp',
];

// Dimensions straight from the container header, so this is not macOS-only and
// needs no image library. WebP stores them three different ways depending on
// which encoder produced the file, and all three appear in this repo.
function webpSize(file) {
  const b = fs.readFileSync(file);
  if (b.toString('ascii', 0, 4) !== 'RIFF' || b.toString('ascii', 8, 12) !== 'WEBP') return null;
  switch (b.toString('ascii', 12, 16)) {
    case 'VP8X': return {width: 1 + b.readUIntLE(24, 3), height: 1 + b.readUIntLE(27, 3)};
    case 'VP8 ': return {width: b.readUInt16LE(26) & 0x3fff, height: b.readUInt16LE(28) & 0x3fff};
    case 'VP8L': {
      const bits = b.readUInt32LE(21);
      return {width: 1 + (bits & 0x3fff), height: 1 + ((bits >> 14) & 0x3fff)};
    }
    default: return null;
  }
}

const manifest = {};
let made = 0;
let skipped = 0;

for (const src of TARGETS) {
  if (!fs.existsSync(src)) {
    console.error('missing source, skipped: ' + src);
    skipped++;
    continue;
  }
  const size = webpSize(src);
  if (!size) {
    console.error('unreadable dimensions, skipped: ' + src);
    skipped++;
    continue;
  }

  const variants = [];
  for (const width of WIDTHS) {
    // Never upscale: a 640px source has no business producing a 660px file, and
    // the srcset already falls back to the source itself.
    if (width >= size.width) continue;
    const out = src.replace(/\.webp$/, '-' + width + '.webp');
    const stale = !fs.existsSync(out) || fs.statSync(out).mtimeMs < fs.statSync(src).mtimeMs;
    if (stale) {
      execFileSync('cwebp', ['-quiet', '-q', QUALITY, '-resize', String(width), '0', src, '-o', out]);
      made++;
    }
    variants.push(width);
  }

  manifest[src] = {width: size.width, height: size.height, variants};
}

const rows = Object.keys(manifest).sort().map(src => {
  const {width, height, variants} = manifest[src];
  return `  ${JSON.stringify(src)}: {width: ${width}, height: ${height}, variants: [${variants.join(', ')}]},`;
});

fs.writeFileSync('site/image-variants.mjs',
  '// GENERATED by scripts/image-variants.mjs — do not edit by hand.\n' +
  '//\n' +
  '// Intrinsic size of every card image, and which -<width>.webp variants exist\n' +
  '// beside it. The build uses this to write a srcset that only ever names files\n' +
  '// that are actually on disk, so a new card image without variants falls back\n' +
  '// to no srcset rather than to a 404.\n' +
  'export const imageVariants = {\n' + rows.join('\n') + '\n};\n');

console.log(`generated ${made} variant file(s) across ${Object.keys(manifest).length} image(s), skipped ${skipped}`);
